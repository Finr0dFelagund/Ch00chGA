#Категории причин решений фильтра «отвечать/молчать» для группировки в статистике.
#Модель должна писать главную причину из этого набора; вольные старые записи
#распознаются правилами по ключевым словам, непокрытое уходит в «другое».
CATEGORY_LABELS = [
    ("обращение", "обращение к боту"),
    ("вопрос", "вопрос по существу"),
    ("продолжение", "продолжение темы"),
    ("событие", "новая тема или событие"),
    ("диалог", "диалог участников"),
    ("шум", "фоновый шум"),
    ("реплика", "короткая реплика"),
    ("без_содержания", "без содержания"),
    ("технические", "технические причины"),
    ("другое", "другое"),
]

_TECHNICAL = {"no_history", "empty", "parse_failed", "error"}


def _has(text: str, *keys) -> bool:
    return any(key in text for key in keys)


def categorize_reason(should: bool, reason) -> str:
    """Возвращает ключ категории для причины решения фильтра."""
    text = (reason or "").strip().lower()
    if not text or text in _TECHNICAL:
        return "технические"
    if text == "mention":
        return "обращение"

    if not should:
        if _has(text, "не к боту", "между собой") or (_has(text, "диалог") and _has(text, "участник")):
            return "диалог"
        if _has(text, "без содержа", "голая ссылка", "ссылка без", "служебн",
                "не должен отвечать", "не нужно отвечать", "не по делу"):
            return "без_содержания"
        if _has(text, "фонов", "шум"):
            return "шум"
        if _has(text, "коротк", "подтверждени", "спс", " вне общения"):
            return "реплика"
    else:
        if _has(text, "без содержа", "голая ссылка", "ссылка без", "служебн"):
            return "без_содержания"
        if _has(text, "обращени"):
            return "обращение"
        if _has(text, "коротк"):
            return "реплика"
        if _has(text, "вопрос"):
            return "вопрос"
        if _has(text, "продолжени", "развити", "участвует"):
            return "продолжение"
        if _has(text, "нов", "событ", "функц"):
            return "событие"
        if _has(text, "фонов", "шум"):
            return "шум"

    if _has(text, "обращени"):
        return "обращение"
    if _has(text, "вопрос"):
        return "вопрос"
    if _has(text, "продолжени", "развити", "участвует"):
        return "продолжение"
    if _has(text, "нов", "событ", "функц"):
        return "событие"
    if _has(text, "диалог"):
        return "диалог"
    if _has(text, "коротк", "подтверждени", "спс"):
        return "реплика"
    if _has(text, "фонов", "шум"):
        return "шум"
    if _has(text, "без содержа", "голая ссылка", "ссылка без"):
        return "без_содержания"
    return "другое"


def category_label(key: str) -> str:
    """Человекочитаемая подпись категории."""
    for k, label in CATEGORY_LABELS:
        if k == key:
            return label
    return key
